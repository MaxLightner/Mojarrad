    private static function insert(string $type, array $row): void {
        $existing = get_page_by_path($row['slug'], OBJECT, $type);
        if ($existing) {
            return;
        }
        $body = wpautop(esc_html(str_replace("\n", "\n\n", $row['text'])));
        $post_id = wp_insert_post(array(
            'post_type' => $type,
            'post_status' => 'publish',
            'post_name' => $row['slug'],
            'post_title' => $row['title'],
            'post_excerpt' => $row['summary'] ?? ($row['subtitle'] ?? ''),
            'post_content' => $body,
        ), true);
        if (is_wp_error($post_id) || !$post_id) {
            return;
        }
        update_post_meta($post_id, '_mojarrad_legacy_import', '2026-10-21');
        if ($type === 'moj_project') {
            $fields = array(
                'subtitle' => $row['subtitle'], 'location' => $row['location'],
                'area' => $row['area'], 'year' => $row['year'],
                'status' => $row['status'], 'demo_cover' => $row['cover'],
                'demo_gallery' => implode(',', $row['gallery']),
            );
            foreach ($fields as $key => $value) {
                update_post_meta($post_id, 'moj_' . $key, $value);
            }
            if (taxonomy_exists('moj_project_status')) {
                wp_set_object_terms($post_id, $row['state'], 'moj_project_status');
            }
        } else {
            update_post_meta($post_id, 'moj_demo_image', $row['img']);
            if (!empty($row['category']) && taxonomy_exists('category')) {
                $term = term_exists($row['category'], 'category');
                if (!$term) {
                    $term = wp_insert_term($row['category'], 'category');
                }
                if (!is_wp_error($term)) {
                    wp_set_post_categories($post_id, array(is_array($term) ? (int)$term['term_id'] : (int)$term), false);
                }
            }
        }
    }
